#!/usr/bin/env python3
"""Generate research/cpp/kb_synergy.inc from the KB's synergy lists (cards and relics).
Emits card-card and relic-card pairs with weights: synergy +1, super-synergy +2, anti-synergy -1."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SIM = "/home/user/sts_lightspeed/include/constants"
def enum_names(path, enum):
    s = open(path).read(); m = re.search(r"enum class %s[^{]*\{(.*?)\};" % enum, s, re.S)
    body = re.sub(r"//.*", "", m.group(1)); return {t.strip().split("=")[0].strip() for t in body.replace("\n", " ").split(",") if t.strip()}
CARDS = enum_names(f"{SIM}/Cards.h", "CardId"); RELICS = enum_names(f"{SIM}/Relics.h", "RelicId")
SPECIAL = {"Strike": "STRIKE_RED", "Defend": "DEFEND_RED", "J.A.X.": "JAX"}
def key(name): return SPECIAL.get(name) or re.sub(r"[^A-Z0-9]+", "_", name.upper().replace("'", "").replace(".", "")).strip("_")
cards = json.load(open(f"{ROOT}/data/ironclad_cards.json")); relics = json.load(open(f"{ROOT}/data/ironclad_relics.json"))
card_ids = {c["name"]: key(c["name"]) for c in cards if key(c["name"]) in CARDS}
relic_ids = {r["name"]: key(r["name"]) for r in relics if key(r["name"]) in RELICS}
missing_c = [c["name"] for c in cards if key(c["name"]) not in CARDS]; missing_r = [r["name"] for r in relics if key(r["name"]) not in RELICS]
cc, rc = {}, {}
def add(d, k, w):
    d[k] = max(d.get(k, -9), w) if w > 0 else min(d.get(k, 9), w)
unk = set()
for c in cards:
    a = card_ids.get(c["name"]);
    if not a: continue
    for lst, w in ((c.get("super_synergies") or [], 2.0), (c.get("synergies") or [], 1.0), (c.get("antisynergies") or [], -1.0)):
        for n in lst:
            if n in card_ids: add(cc, (a, card_ids[n]), w)
            elif n in relic_ids: add(rc, (relic_ids[n], a), w)
            elif key(n) in CARDS: add(cc, (a, key(n)), w)   # colorless card / curse
            else: unk.add(n)
for r in relics:
    rid = relic_ids.get(r["name"])
    if not rid: continue
    for lst, w in ((r.get("super_synergies") or [], 2.0), (r.get("synergies") or [], 1.0), (r.get("antisynergies") or [], -1.0)):
        for n in lst:
            if n in card_ids: add(rc, (rid, card_ids[n]), w)
            elif n in relic_ids: pass  # relic-relic: unused
            elif key(n) in CARDS: add(rc, (rid, key(n)), w)
            else: unk.add(n)
with open(f"{ROOT}/research/cpp/kb_synergy.inc", "w") as f:
    f.write("// generated by research/tools/gen_kb_synergy.py from data/ironclad_{cards,relics}.json — do not edit\n")
    f.write("// card-card pairs (a lists b): weight +1 synergy, +2 super, -1 anti\n")
    f.write("static const KbCardSyn kKbCardSyn[] = {\n" + "".join(f"  {{CardId::{a}, CardId::{b}, {w:.1f}f}},\n" for (a, b), w in sorted(cc.items())) + "};\n")
    f.write("static const KbRelicSyn kKbRelicSyn[] = {\n" + "".join(f"  {{RelicId::{r}, CardId::{c}, {w:.1f}f}},\n" for (r, c), w in sorted(rc.items())) + "};\n")
print(f"card-card pairs {len(cc)}, relic-card pairs {len(rc)}; unmapped cards {missing_c}; unmapped relics {missing_r[:6]}{'...' if len(missing_r)>6 else ''} ({len(missing_r)}); unknown synergy names {len(unk)}: {sorted(unk)[:10]}")
