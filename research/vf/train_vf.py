#!/usr/bin/env python3
"""Train the combat value MLP from logged (features, outcome) rows and export C++ weights.

Input rows are binary float32 written by FairAgent (vf_log): DIM features followed by
[win, final_hp, target_value, battle_id]. Target = search-unit terminal value
(win: 35 + hp + 4*potions; loss: partial credit), i.e. exactly what the search backs up.

usage: train_vf.py DATA_DIR [--out research/cpp/vf_weights.inc] [--hidden 64] [--epochs 30]
"""
import argparse, glob, os, sys, time
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DIM = 204  # must match features.h
EXTRA = 4


def load(data_dir):
    files = sorted(glob.glob(os.path.join(data_dir, "*.bin")))
    arrs = [np.fromfile(f, dtype=np.float32) for f in files]
    a = np.concatenate(arrs) if arrs else np.zeros(0, np.float32)
    n = a.size // (DIM + EXTRA)
    a = a[: n * (DIM + EXTRA)].reshape(n, DIM + EXTRA)
    return a[:, :DIM], a[:, DIM], a[:, DIM + 1], a[:, DIM + 2], a[:, DIM + 3].astype(np.int64)


def export(path, W1, b1, W2, b2, trained=1):
    H, D = W1.shape
    with open(path, "w") as f:
        f.write(f"// generated by research/vf/train_vf.py — do not edit\n")
        f.write(f"constexpr int VF_W_DIM = {D};\nconstexpr int VF_H = {H};\nconstexpr int VF_TRAINED = {trained};\n")
        f.write("static const float W1[VF_H * VF_W_DIM] = {" + ",".join(f"{v:.6g}" for v in W1.ravel()) + "};\n")
        f.write("static const float B1[VF_H] = {" + ",".join(f"{v:.6g}" for v in b1) + "};\n")
        f.write("static const float W2[VF_H] = {" + ",".join(f"{v:.6g}" for v in W2) + "};\n")
        f.write(f"static const float B2 = {float(b2):.6g};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("data_dir")
    ap.add_argument("--out", default=os.path.join(ROOT, "cpp", "vf_weights.inc"))
    ap.add_argument("--hidden", type=int, default=64)
    ap.add_argument("--epochs", type=int, default=30)
    ap.add_argument("--placeholder", action="store_true", help="write zero weights (untrained) and exit")
    a = ap.parse_args()
    if a.placeholder:
        export(a.out, np.zeros((a.hidden, DIM), np.float32), np.zeros(a.hidden, np.float32),
               np.zeros(a.hidden, np.float32), 0.0, trained=0)
        print("placeholder written", a.out); return

    import torch, torch.nn as nn
    torch.manual_seed(0)
    X, win, hp, y, bid = load(a.data_dir)
    print(f"rows={len(y)} battles={len(np.unique(bid))} win_rate={win.mean():.3f} target mean={y.mean():.2f} sd={y.std():.2f}")
    # split by battle id so correlated rows from one fight don't leak into validation
    rng = np.random.RandomState(0)
    ub = np.unique(bid); rng.shuffle(ub)
    val_b = set(ub[: len(ub) // 5].tolist())
    vmask = np.array([b in val_b for b in bid])
    Xt, yt = torch.tensor(X[~vmask]), torch.tensor(y[~vmask])
    Xv, yv = torch.tensor(X[vmask]), torch.tensor(y[vmask])
    ymean, ysd = float(yt.mean()), float(yt.std() + 1e-6)

    model = nn.Sequential(nn.Linear(DIM, a.hidden), nn.ReLU(), nn.Linear(a.hidden, 1))
    opt = torch.optim.Adam(model.parameters(), lr=2e-3, weight_decay=1e-5)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, a.epochs)
    bs = 1024
    base_rmse = float(torch.sqrt(((yv - ymean) ** 2).mean()))
    t0 = time.time()
    for ep in range(a.epochs):
        model.train()
        perm = torch.randperm(len(yt))
        for i in range(0, len(yt), bs):
            idx = perm[i:i + bs]
            pred = model(Xt[idx]).squeeze(1)
            loss = ((pred - (yt[idx] - ymean) / ysd) ** 2).mean()
            opt.zero_grad(); loss.backward(); opt.step()
        sched.step()
        model.eval()
        with torch.no_grad():
            pv = model(Xv).squeeze(1) * ysd + ymean
            rmse = float(torch.sqrt(((pv - yv) ** 2).mean()))
            # win-classification sanity: value above the loss/win boundary (35) predicts a win
            acc = float(((pv > 35) == (yv > 35)).float().mean())
        print(f"ep {ep+1:2d} val_rmse={rmse:.2f} (predict-mean {base_rmse:.2f}) win_acc={acc:.3f} {time.time()-t0:.0f}s")

    W1 = model[0].weight.detach().numpy(); b1 = model[0].bias.detach().numpy()
    W2 = (model[2].weight.detach().numpy().ravel() * ysd); b2 = float(model[2].bias.detach().numpy()[0] * ysd + ymean)
    export(a.out, W1, b1, W2, b2, trained=1)
    print("exported", a.out, "val_rmse", round(rmse, 2), "baseline", round(base_rmse, 2))


if __name__ == "__main__":
    main()
