#!/usr/bin/env python3
"""MLP move prior (Phase B, stronger than the bilinear model). Trained on root visit distributions.

logit(a) = W2 . relu(W1 . [state(204) ; E[tok_a] + up_a*E_up (16) ; tf_a (4)] + b1) + b2
softmax over the node's legal actions; CE against the visit distribution.
Inference cost ~ (204+16+4)*64 MACs per action -> used only at shallow tree depth in C++.
usage: train_policy_mlp.py DATA_DIR [--out research/cpp/pfm_weights.inc] [--k 16] [--hidden 64] [--epochs 8]
"""
import argparse, os, sys, time
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import train_policy as tp  # noqa: E402

S_DIM, N_TOK, T_DIM = tp.S_DIM, tp.N_TOK, tp.T_DIM


def export(path, E, Eup, W1, b1, W2, b2, k, hidden, trained=1):
    for arr in (E, Eup, W1, b1, W2, np.array([b2])):
        if not np.isfinite(arr).all():
            raise SystemExit("refusing to export non-finite weights")
    with open(path, "w") as f:
        f.write("// generated by research/vf/train_policy_mlp.py — do not edit\n")
        f.write(f"constexpr int PFM_S_DIM = {S_DIM};\nconstexpr int PFM_K = {k};\nconstexpr int PFM_T = {T_DIM};\n")
        f.write(f"constexpr int PFM_IN = {S_DIM + k + T_DIM};\nconstexpr int PFM_H = {hidden};\nconstexpr int PFM_N_TOK = {N_TOK};\nconstexpr int PFM_TRAINED = {trained};\n")
        f.write("static const float PFM_E[PFM_N_TOK * PFM_K] = {" + ",".join(f"{v:.6g}" for v in E.ravel()) + "};\n")
        f.write("static const float PFM_EUP[PFM_K] = {" + ",".join(f"{v:.6g}" for v in Eup) + "};\n")
        f.write("static const float PFM_W1[PFM_H * PFM_IN] = {" + ",".join(f"{v:.6g}" for v in W1.ravel()) + "};\n")
        f.write("static const float PFM_B1[PFM_H] = {" + ",".join(f"{v:.6g}" for v in b1) + "};\n")
        f.write("static const float PFM_W2[PFM_H] = {" + ",".join(f"{v:.6g}" for v in W2) + "};\n")
        f.write(f"static const float PFM_B2 = {float(b2):.6g};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("data_dir"); ap.add_argument("--out", default=os.path.join(ROOT, "cpp", "pfm_weights.inc"))
    ap.add_argument("--k", type=int, default=16); ap.add_argument("--hidden", type=int, default=64)
    ap.add_argument("--epochs", type=int, default=8); ap.add_argument("--placeholder", action="store_true")
    a = ap.parse_args()
    k, H = a.k, a.hidden
    if a.placeholder:
        D = S_DIM + k + T_DIM
        export(a.out, np.zeros((N_TOK, k), np.float32), np.zeros(k, np.float32), np.zeros((H, D), np.float32),
               np.zeros(H, np.float32), np.zeros(H, np.float32), 0.0, k, H, trained=0)
        print("placeholder written", a.out); return

    import torch, torch.nn as nn
    torch.manual_seed(0)
    states, toks, ups, tfs, vis, dec = tp.load(a.data_dir)
    D = len(states); print(f"decisions={D} actions={sum(len(t) for t in toks)}")
    S = torch.tensor(np.stack(states)); TOK = torch.tensor(np.concatenate(toks)); UP = torch.tensor(np.concatenate(ups))
    TF = torch.tensor(np.concatenate(tfs)); V = torch.tensor(np.concatenate(vis)); DEC = torch.tensor(np.concatenate(dec))
    rng = np.random.RandomState(0); perm = rng.permutation(D); val_d = torch.tensor(np.sort(perm[: D // 5]))
    is_val = torch.isin(DEC, val_d)
    E = nn.Embedding(N_TOK, k); Eup = nn.Parameter(torch.zeros(k))
    L1 = nn.Linear(S_DIM + k + T_DIM, H); L2 = nn.Linear(H, 1)
    params = list(E.parameters()) + [Eup] + list(L1.parameters()) + list(L2.parameters())
    opt = torch.optim.Adam(params, lr=2e-3, weight_decay=1e-6)
    tgt = V / torch.zeros(D).scatter_add(0, DEC, V)[DEC]
    cnt = torch.zeros(D).scatter_add(0, DEC, torch.ones_like(V))

    def logits(idx_actions):
        x = torch.cat([S[DEC[idx_actions]], E(TOK[idx_actions]) + UP[idx_actions].unsqueeze(1) * Eup, TF[idx_actions]], 1)
        return L2(torch.relu(L1(x))).squeeze(1)

    def ce(mask_actions):
        # softmax per decision over ALL legal actions (needs every action of each decision in the batch)
        lg = torch.full((len(DEC),), -1e30)
        idx = torch.nonzero(mask_actions).squeeze(1)
        lg[idx] = logits(idx)
        m = torch.full((D,), -1e30).scatter_reduce(0, DEC, lg, reduce="amax")
        ex = torch.exp(lg - m[DEC]); z = torch.zeros(D).scatter_add(0, DEC, ex)
        logp = lg - m[DEC] - torch.log(z[DEC])
        return -(tgt * logp)[mask_actions].sum() / max(1, int(mask_actions.sum()))

    with torch.no_grad():
        unif = float((-(tgt * torch.log(1.0 / cnt[DEC])))[is_val].sum() / int(is_val.sum()))
        ent = float((-(tgt * torch.log(tgt.clamp_min(1e-9))))[is_val].sum() / int(is_val.sum()))
    print(f"val baselines: uniform CE={unif:.4f}  target entropy={ent:.4f}")
    # mini-batches by decision id (all actions of a decision stay together)
    train_d = torch.tensor(np.sort(perm[D // 5:])); bs_dec = 2048; t0 = time.time()
    for ep in range(a.epochs):
        order = train_d[torch.randperm(len(train_d))]
        for i in range(0, len(order), bs_dec):
            dmask = torch.isin(DEC, order[i:i + bs_dec])
            loss = ce(dmask); opt.zero_grad(); loss.backward(); opt.step()
        with torch.no_grad():
            lv = float(ce(is_val))
        print(f"ep {ep+1:2d} val_ce={lv:.4f} (uniform {unif:.4f}, floor {ent:.4f}, captured {(unif-lv)/(unif-ent):.0%}) {time.time()-t0:.0f}s")
    export(a.out, E.weight.detach().numpy(), Eup.detach().numpy(), L1.weight.detach().numpy(), L1.bias.detach().numpy(),
           L2.weight.detach().numpy().ravel(), float(L2.bias.detach().numpy()[0]), k, H, trained=1)
    print("exported", a.out)


if __name__ == "__main__":
    main()
