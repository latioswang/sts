#!/usr/bin/env python3
"""Train the bilinear move prior from logged root visit distributions (Phase B) and export C++ weights.

Log format (binary float32, per decision): [204 state feats][nA][nA x (token, tf0..tf3, visits)]
Model: h = W s + b (K); logit_a = h.E[tok_a] + up_a*(h.E_up) + AB[tok_a] + T.tf_a ; CE vs visit distribution.
usage: train_policy.py DATA_DIR [--out research/cpp/pf_weights.inc] [--k 16] [--epochs 10] [--placeholder]
"""
import argparse, glob, os, time
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
S_DIM, N_TOK, T_DIM = 204, 434, 4


def load(data_dir, max_decisions=None):
    states, toks, ups, tfs, vis, dec = [], [], [], [], [], []
    d = 0
    for f in sorted(glob.glob(os.path.join(data_dir, "pol_*.bin"))):
        a = np.fromfile(f, dtype=np.float32)
        i = 0
        while i + S_DIM + 1 <= a.size:
            s = a[i:i + S_DIM]; i += S_DIM
            n = int(a[i]); i += 1
            if n <= 0 or i + n * 7 > a.size: break
            blk = a[i:i + n * 7].reshape(n, 7); i += n * 7
            states.append(s); toks.append(blk[:, 0].astype(np.int64)); ups.append(blk[:, 1])
            tfs.append(blk[:, 2:6]); vis.append(blk[:, 6]); dec.append(np.full(n, d)); d += 1
            if max_decisions and d >= max_decisions: break
    return states, toks, ups, tfs, vis, dec


def export(path, W, b, E, Eup, AB, T, k, trained=1):
    import numpy as _np
    for _a in [v for v in locals().values() if isinstance(v, _np.ndarray)]:
        if not _np.isfinite(_a).all():
            raise SystemExit("refusing to export non-finite weights")
    with open(path, "w") as f:
        f.write("// generated by research/vf/train_policy.py — do not edit\n")
        f.write(f"constexpr int PF_S_DIM = {S_DIM};\nconstexpr int PF_K = {k};\nconstexpr int PF_N_TOK = {N_TOK};\nconstexpr int PF_TRAINED = {trained};\n")
        f.write("static const float PF_W[PF_K * PF_S_DIM] = {" + ",".join(f"{v:.6g}" for v in W.ravel()) + "};\n")
        f.write("static const float PF_B[PF_K] = {" + ",".join(f"{v:.6g}" for v in b) + "};\n")
        f.write("static const float PF_E[PF_N_TOK * PF_K] = {" + ",".join(f"{v:.6g}" for v in E.ravel()) + "};\n")
        f.write("static const float PF_EUP[PF_K] = {" + ",".join(f"{v:.6g}" for v in Eup) + "};\n")
        f.write("static const float PF_AB[PF_N_TOK] = {" + ",".join(f"{v:.6g}" for v in AB) + "};\n")
        f.write("static const float PF_T[4] = {" + ",".join(f"{v:.6g}" for v in T) + "};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("data_dir"); ap.add_argument("--out", default=os.path.join(ROOT, "cpp", "pf_weights.inc"))
    ap.add_argument("--k", type=int, default=16); ap.add_argument("--epochs", type=int, default=10)
    ap.add_argument("--placeholder", action="store_true")
    a = ap.parse_args()
    k = a.k
    if a.placeholder:
        export(a.out, np.zeros((k, S_DIM), np.float32), np.zeros(k, np.float32), np.zeros((N_TOK, k), np.float32),
               np.zeros(k, np.float32), np.zeros(N_TOK, np.float32), np.zeros(4, np.float32), k, trained=0)
        print("placeholder written", a.out); return

    import torch, torch.nn as nn, torch.nn.functional as F
    torch.manual_seed(0)
    states, toks, ups, tfs, vis, dec = load(a.data_dir)
    D = len(states); print(f"decisions={D} actions={sum(len(t) for t in toks)}")
    S = torch.tensor(np.stack(states)); TOK = torch.tensor(np.concatenate(toks)); UP = torch.tensor(np.concatenate(ups))
    TF = torch.tensor(np.concatenate(tfs)); V = torch.tensor(np.concatenate(vis)); DEC = torch.tensor(np.concatenate(dec))
    rng = np.random.RandomState(0); perm = rng.permutation(D); val_d = torch.tensor(np.sort(perm[: D // 5]))
    is_val_action = torch.isin(DEC, val_d)

    W = nn.Linear(S_DIM, k); E = nn.Embedding(N_TOK, k); Eup = nn.Parameter(torch.zeros(k)); AB = nn.Parameter(torch.zeros(N_TOK)); T = nn.Parameter(torch.zeros(4))
    params = list(W.parameters()) + list(E.parameters()) + [Eup, AB, T]
    opt = torch.optim.Adam(params, lr=3e-3, weight_decay=1e-6)

    def logits_all():
        h = W(S)                                   # D x k
        ha = h[DEC]                                # A x k
        e = E(TOK) + UP.unsqueeze(1) * Eup         # A x k
        return (ha * e).sum(1) + AB[TOK] + TF @ T  # A

    def loss_on(mask):
        lg = logits_all()
        # per-decision softmax via logsumexp scatter
        m = torch.full((D,), -1e30); m = m.scatter_reduce(0, DEC, lg, reduce="amax")
        ex = torch.exp(lg - m[DEC]); z = torch.zeros(D).scatter_add(0, DEC, ex)
        logp = lg - m[DEC] - torch.log(z[DEC])
        tgt = V / torch.zeros(D).scatter_add(0, DEC, V)[DEC]
        ce = -(tgt * logp)
        return ce[mask].sum() / max(1, int(mask.sum().item()))

    # interpretability baselines: uniform prior CE and the target distribution's own entropy (CE lower bound)
    with torch.no_grad():
        cnt = torch.zeros(D).scatter_add(0, DEC, torch.ones_like(V))
        tgt_all = V / torch.zeros(D).scatter_add(0, DEC, V)[DEC]
        unif_ce = float((-(tgt_all * torch.log(1.0 / cnt[DEC])))[is_val_action].sum() / max(1, int(is_val_action.sum())))
        ent = float((-(tgt_all * torch.log(tgt_all.clamp_min(1e-9))))[is_val_action].sum() / max(1, int(is_val_action.sum())))
    print(f"val baselines: uniform-prior CE={unif_ce:.4f}  target entropy (lower bound)={ent:.4f}")
    t0 = time.time()
    for ep in range(a.epochs):
        opt.zero_grad(); l = loss_on(~is_val_action); l.backward(); opt.step()
        with torch.no_grad():
            lv = float(loss_on(is_val_action))
        print(f"ep {ep+1:2d} train_ce={float(l):.4f} val_ce={lv:.4f} {time.time()-t0:.0f}s")
    export(a.out, W.weight.detach().numpy(), W.bias.detach().numpy(), E.weight.detach().numpy(),
           Eup.detach().numpy(), AB.detach().numpy(), T.detach().numpy(), k, trained=1)
    print("exported", a.out)


if __name__ == "__main__":
    main()
