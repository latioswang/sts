#!/usr/bin/env python3
"""Train V_run = P(win | run state) from rv_log rows and export C++ weights (Phase C).

Rows: RV_DIM float32 features + [win, floor, act, run_id]. Export: research/cpp/rv_weights.inc
usage: train_run.py DATA_DIR [--out ...] [--hidden 64] [--epochs 20] [--placeholder]
"""
import argparse, glob, os, time
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DIM = 666
EXTRA = 4


def load(data_dir):
    files = sorted(glob.glob(os.path.join(data_dir, "run_*.bin")))
    arrs = [np.fromfile(f, dtype=np.float32) for f in files]
    a = np.concatenate(arrs) if arrs else np.zeros(0, np.float32)
    n = a.size // (DIM + EXTRA)
    a = a[: n * (DIM + EXTRA)].reshape(n, DIM + EXTRA)
    return a[:, :DIM], a[:, DIM], a[:, DIM + 1], a[:, DIM + 2], a[:, DIM + 3].astype(np.int64)


def export(path, W1, b1, W2, b2, trained=1):
    H, D = W1.shape
    import numpy as _np
    for _a in [v for v in locals().values() if isinstance(v, _np.ndarray)]:
        if not _np.isfinite(_a).all():
            raise SystemExit("refusing to export non-finite weights")
    with open(path, "w") as f:
        f.write("// generated by research/vf/train_run.py — do not edit\n")
        f.write(f"constexpr int RV_W_DIM = {D};\nconstexpr int RV_H = {H};\nconstexpr int RV_TRAINED = {trained};\n")
        f.write("static const float RV_W1[RV_H * RV_W_DIM] = {" + ",".join(f"{v:.6g}" for v in W1.ravel()) + "};\n")
        f.write("static const float RV_B1[RV_H] = {" + ",".join(f"{v:.6g}" for v in b1) + "};\n")
        f.write("static const float RV_W2[RV_H] = {" + ",".join(f"{v:.6g}" for v in W2) + "};\n")
        f.write(f"static const float RV_B2 = {float(b2):.6g};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("data_dir")
    ap.add_argument("--out", default=os.path.join(ROOT, "cpp", "rv_weights.inc"))
    ap.add_argument("--hidden", type=int, default=64)
    ap.add_argument("--epochs", type=int, default=20)
    ap.add_argument("--placeholder", action="store_true")
    a = ap.parse_args()
    if a.placeholder:
        export(a.out, np.zeros((a.hidden, DIM), np.float32), np.zeros(a.hidden, np.float32),
               np.zeros(a.hidden, np.float32), 0.0, trained=0)
        print("placeholder written", a.out); return

    import torch, torch.nn as nn
    torch.manual_seed(0)
    X, win, floor, act, rid = load(a.data_dir)
    print(f"rows={len(win)} runs={len(np.unique(rid))} win_rate(rows)={win.mean():.3f}")
    rng = np.random.RandomState(0)
    ur = np.unique(rid); rng.shuffle(ur)
    val_r = set(ur[: len(ur) // 5].tolist())
    vmask = np.array([r in val_r for r in rid])
    Xt, yt = torch.tensor(X[~vmask]), torch.tensor(win[~vmask])
    Xv, yv = torch.tensor(X[vmask]), torch.tensor(win[vmask])
    model = nn.Sequential(nn.Linear(DIM, a.hidden), nn.ReLU(), nn.Linear(a.hidden, 1))
    opt = torch.optim.Adam(model.parameters(), lr=1e-3, weight_decay=1e-4)
    lossf = nn.BCEWithLogitsLoss()
    bs = 512
    base = float(yv.mean()); base_ll = -(base * np.log(base + 1e-9) + (1 - base) * np.log(1 - base + 1e-9))
    t0 = time.time()
    for ep in range(a.epochs):
        model.train(); perm = torch.randperm(len(yt))
        for i in range(0, len(yt), bs):
            idx = perm[i:i + bs]
            loss = lossf(model(Xt[idx]).squeeze(1), yt[idx])
            opt.zero_grad(); loss.backward(); opt.step()
        model.eval()
        with torch.no_grad():
            lv = model(Xv).squeeze(1)
            ll = float(lossf(lv, yv)); acc = float(((lv > 0).float() == yv).float().mean())
        print(f"ep {ep+1:2d} val_logloss={ll:.4f} (predict-base {base_ll:.4f}) acc={acc:.3f} {time.time()-t0:.0f}s")
    W1 = model[0].weight.detach().numpy(); b1 = model[0].bias.detach().numpy()
    W2 = model[2].weight.detach().numpy().ravel(); b2 = float(model[2].bias.detach().numpy()[0])
    export(a.out, W1, b1, W2, b2, trained=1)  # output is a logit; C++ applies sigmoid
    print("exported", a.out)


if __name__ == "__main__":
    main()
